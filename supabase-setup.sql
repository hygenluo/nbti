-- NBTI 测试记录表：在 Supabase Dashboard → SQL Editor 里整段粘贴执行一次即可

create table if not exists public.test_results (
  id bigint generated by default as identity primary key,
  label text not null,
  label_cn text not null,
  title text not null,
  keywords jsonb not null,
  scores jsonb not null,
  answers jsonb not null,
  created_at timestamptz not null default now()
);

alter table public.test_results enable row level security;

-- 匿名角色（publishable key）只允许：写入新记录 + 读取记录（用于统计）
-- 不允许修改/删除，防止恶意篡改
create policy "anyone can submit a result"
  on public.test_results for insert
  to anon
  with check (true);

create policy "anyone can read results"
  on public.test_results for select
  to anon
  using (true);

grant insert, select on public.test_results to anon;

-- 统计视图：按标签聚合一栏人数
create or replace view public.test_results_stats as
  select label, label_cn as name, count(*)::int as count
  from public.test_results
  group by label, label_cn
  order by count(*) desc;

grant select on public.test_results_stats to anon;
